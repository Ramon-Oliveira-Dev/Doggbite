export function getSongWaveform(songTitle?: string): number[] {
  if (songTitle && PRECOMPUTED_WAVEFORMS[songTitle]) {
    return PRECOMPUTED_WAVEFORMS[songTitle];
  }
  // Deterministic procedural fallback for any other song
  const bars: number[] = [];
  const seed = (songTitle || "DOGGBITE").split("").reduce((acc, c) => acc + c.charCodeAt(0), 42);
  for (let i = 0; i < 96; i++) {
    const val = 0.2 + 0.7 * Math.abs(Math.sin((i + seed) * 0.35) * Math.cos(i * 0.21));
    bars.push(Math.round(val * 100) / 100);
  }
  return bars;
}
